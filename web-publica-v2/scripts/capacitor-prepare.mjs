import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dist=path.join(root,'dist');
const w2=path.join(dist,'w2','index.html');
if(!fs.existsSync(w2))throw new Error('El build no genero dist/w2/index.html.');
let html=fs.readFileSync(w2,'utf8');
html=html.replace("const preferred=matchMedia('(prefers-color-scheme: light)').matches?'light':'dark';document.documentElement.dataset.w2Theme=saved||preferred","document.documentElement.dataset.w2Theme=saved||'dark'");
html=html.replace(/<script src="\/w2\/pwa-register\.js" defer><\/script>/g,'');
fs.writeFileSync(path.join(dist,'index.html'),html,'utf8');
console.log('CAPACITOR_W2_PRODUCCION_PREPARADA_OK');
